DEPFILE_FLAGS = ("-MD", "-MMD", "-MF", "-MT")
HPL_MODULE_DIR = os.sep + "kernel" + os.sep + "extended" + os.sep + "hpl" + os.sep


def wrapper_die(msg):
    sys.stderr.write("[hpl_preprocessor] %s\n" % msg)
    sys.exit(1)


def wrapper_parse_config_h(args):
    """Extract the out config.h path from the -imacros flag and read the
    HPL switches plus the core bit from it."""
    config_h = None
    for i, arg in enumerate(args):
        if arg == "-imacros" and i + 1 < len(args):
            config_h = os.path.abspath(args[i + 1])
        elif arg.startswith("-imacros") and len(arg) > len("-imacros"):
            config_h = os.path.abspath(arg[len("-imacros"):])
    if config_h is None or not os.path.isfile(config_h):
        return None
    values = {}
    with open(config_h, "r", errors="replace") as f:
        for line in f:
            m = re.match(r"#define\s+(LOSCFG_[A-Z0-9_]+)\s+(\S+)", line)
            if m:
                values[m.group(1)] = m.group(2)
    values["__config_h__"] = config_h
    return values


def wrapper_split_compile_command(args):
    """Return (flags, source, output) of a 'gcc ... -c src -o obj' command."""
    flags = []
    source = None
    output = None
    i = 0
    while i < len(args):
        arg = args[i]
        if arg == "-o" and i + 1 < len(args):
            output = args[i + 1]
            i += 2
            continue
        if arg == "-c":
            i += 1
            continue
        if arg.endswith(".c") and not arg.startswith("-"):
            source = arg
            i += 1
            continue
        flags.append(arg)
        i += 1
    return flags, source, output


def wrapper_drop_depfile_flags(flags):
    """Remove -MD/-MMD and the argument of -MF/-MT."""
    out = []
    i = 0
    while i < len(flags):
        arg = flags[i]
        if arg in ("-MD", "-MMD"):
            i += 1
            continue
        if arg in ("-MF", "-MT") and i + 1 < len(flags):
            i += 2
            continue
        out.append(arg)
        i += 1
    return out


def wrapper_preprocess_out_path(out_dir, source):
    """Mirror the fbb relative-path rule: the tail of the lowercased source
    path starting at 'lite' (or 'bounds_checking_function'); a digest prefix
    keeps unrelated roots collision-free."""
    rel = None
    lower = os.path.abspath(source).lower()
    m = re.search(r"lite.*$", lower)
    if m:
        rel = m.group(0)
    else:
        m = re.search(r"bounds_checking_function.*$", lower)
        if m:
            rel = m.group(0)
    if rel is None:
        digest = hashlib.sha256(lower.encode()).hexdigest()[:12]
        rel = digest + "_" + os.path.basename(lower)
    return os.path.join(out_dir, "hpl", "preprocess", rel)


def wrapper_run(cmd):
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          universal_newlines=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout)
        sys.stderr.write(proc.stderr)
        wrapper_die("command failed: %s" % " ".join(cmd))
    return proc


def run_as_compiler_wrapper(real_tool, rest):
    """Entry point of the compiler wrapper mode: real_tool is the tool name
    carried by argv[0], rest is the original command line."""
    if not rest:
        wrapper_die("no tool arguments")

    # Only 'tool -c something.c -o x.o' compile steps are candidates.
    flags, source, output = wrapper_split_compile_command(rest)
    if source is None or output is None:
        os.execvp(real_tool, [real_tool] + rest)

    cfg = wrapper_parse_config_h(rest)
    if cfg is None or "LOSCFG_KERNEL_HPL_SCRIPT_PREPROCESSOR" not in cfg:
        os.execvp(real_tool, [real_tool] + rest)

    # The hpl module itself is never preprocessed (matches the fbb
    # MODULE_NAME == "hpl" exclusion).
    if HPL_MODULE_DIR in os.path.abspath(source):
        os.execvp(real_tool, [real_tool] + rest)

    config_h = cfg["__config_h__"]
    out_dir = os.path.dirname(config_h)  # out/<board>/<product>
    core_bit = cfg.get("LOSCFG_KERNEL_HPL_CORE_BIT", "32")
    emulation = "TRUE" if "LOSCFG_DEBUG_HPL_EMULATION" in cfg else "FALSE"
    static_info = "TRUE" if "LOSCFG_KERNEL_HPL_STATIC_INFO" in cfg else "FALSE"

    pre_file = wrapper_preprocess_out_path(out_dir, source)
    os.makedirs(os.path.dirname(pre_file), exist_ok=True)
    metadata_dir = os.path.join(out_dir, "hpl", "preprocess")

    # 1) Preprocess with the real flags; depfile flags are forwarded so the
    #    generated .d keeps tracking the true header dependencies.
    wrapper_run([real_tool] + flags + ["-E", "-o", pre_file, source])

    # 2) Rewrite the HP_LOG expansions (fmt id pre-allocation + metadata),
    #    re-entering this script in its preprocessing mode. realpath is
    #    essential here: this file was reached through a symlink, whose name
    #    would re-trigger the wrapper dispatch.
    wrapper_run([sys.executable or "python3", os.path.realpath(__file__),
                 "0", pre_file, core_bit, metadata_dir, emulation, static_info])

    # 3) Compile the rewritten file with the original command line; depfile
    #    flags were already consumed by step 1, do not let them overwrite
    #    the dependency file with a rewritten-file-only view. The expansion
    #    turns macros into bare code, which strips gcc's macro-argument
    #    exemption from -Wtautological-compare: every such diagnostic on an
    #    expansion file is a macro artefact (source-level ones were already
    #    rejected by -Werror in ordinary builds), so silence that warning.
    wrapper_run([real_tool] + wrapper_drop_depfile_flags(flags) +
                ["-Wno-tautological-compare", "-c", pre_file, "-o", output])


def gen_toolchain_dir(out_dir):
    """Toolchain generation mode: materialise the wrapper toolchain directory
    under the product out dir as a build-time artefact. The gcc entry is a
    symlink to this script (the wrapper mode dispatches on argv[0]); the
    remaining tool names are symlinks to the real cross tools found in PATH,
    so the directory adapts to whichever toolchain is installed."""
    here = os.path.realpath(__file__)
    dst_dir = os.path.join(out_dir, "hpl", "toolchain")
    os.makedirs(dst_dir, exist_ok=True)
    entries = {"arm-none-eabi-gcc": os.path.relpath(here, dst_dir)}
    for tool in ("g++", "ar", "nm", "objcopy", "objdump", "ranlib", "size", "strip"):
        real = shutil.which("arm-none-eabi-" + tool)
        if real is None:
            wrapper_die("cross tool arm-none-eabi-%s not found in PATH" % tool)
        entries["arm-none-eabi-" + tool] = real
    for name, target in entries.items():
        link = os.path.join(dst_dir, name)
        if os.path.islink(link) and os.readlink(link) == target:
            continue
        if os.path.lexists(link):
            os.remove(link)
        os.symlink(target, link)


# argv[1]: independent build module number
# argv[2]: c source file after preprocessing
# argv[3]: processor bit
# argv[4]: metadata file path
# argv[5]: emulation
# argv[6]: file info
if __name__ == '__main__':
    tool_name = os.path.basename(sys.argv[0])
    if tool_name.startswith("arm-none-eabi-"):
        # Executed through a wrapper toolchain symlink: compiler wrapper mode.
        run_as_compiler_wrapper(tool_name, sys.argv[1:])
        sys.exit(0)
    if len(sys.argv) >= 3 and sys.argv[1] == "--gen-toolchain":
        gen_toolchain_dir(sys.argv[2])
        sys.exit(0)

    if len(sys.argv) != 7:
        logging.error("input invalid: %s", sys.argv[2])
        sys.exit(1)

    logger_file = sys.argv[2]
    if not os.path.exists(logger_file):
        logging.error("input file %s not exist", logger_file)
        sys.exit(1)

    command = "grep -w \"\s*do\s*{\s*OsHplLoggerHook\" " + logger_file
    out_text, return_code = Utils.run_shell_return(command, None)
    if return_code not in (0, 1):
        Utils.err_exit("{0} return {1}".format(command, return_code))

    # preprocessor file do not contain log interface.
    if not out_text:
        shutil.copy(logger_file, logger_file + '.i')
        sys.exit()

    extrace_function_line_info(logger_file)

    MODULE_NUM = int(sys.argv[1])
    if MODULE_NUM > 0xFF:
        logging.error("input module number %d invalud", MODULE_NUM)
        sys.exit(1)

    PROCESSOR_BIT = int(sys.argv[3])
    metadata_filepath = sys.argv[4]
    emulation = sys.argv[5]

    if sys.argv[6] == "TRUE":
        FILE_STATIC_INFO = True

    if PROCESSOR_BIT not in (32, 64):
        logging.error("process bit %d wrong", PROCESSOR_BIT)
        sys.exit(1)

    if emulation == "TRUE":
        metadata_filepath = metadata_filepath + os.sep + 'Metadata.c'
    else:
        metadata_filepath = metadata_filepath + os.sep + 'Metadata_' + str(MODULE_NUM)

    atomic_file_path = sys.argv[4] + os.sep + 'atomic_' + str(MODULE_NUM)
    # open with write only | open with creat | open with append
    metadata_file_flags = os.O_WRONLY | os.O_CREAT | os.O_APPEND
    # Write by owner | Read by owner | Read by group | Read by others
    metadata_file_modes = stat.S_IWUSR | stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH
    with os.fdopen(os.open(metadata_filepath, metadata_file_flags, metadata_file_modes), 'a+') as metadata_fd:

        # Lock metadata file to ensure format Id is global unique.
        if emulation == "TRUE":
            fcntl.flock(metadata_fd.fileno(), fcntl.LOCK_EX)

        # open with write only | open with creat | open with trunc
        atomic_file_flags = os.O_RDWR | os.O_CREAT
        with os.fdopen(os.open(atomic_file_path, atomic_file_flags, metadata_file_modes), 'r+') as atomic_fd:
            prase_file(logger_file, metadata_fd, emulation, atomic_fd)

        if emulation == "TRUE":
            fcntl.flock(metadata_fd.fileno(), fcntl.LOCK_UN)
