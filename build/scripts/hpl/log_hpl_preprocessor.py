'''
Description: Parse high performance log to calculate the arguments number and type

The script has three entry modes:
  1. Preprocessing mode (fbb compatible): argv = <moduleId> <preprocessed .c>
     <processor bit> <metadata dir> <emulation> <file info>. Analyzes the
     compiler expansion, pre-allocates format ids and rewrites the log calls.
  2. Compiler wrapper mode (liteos_m GN adaptation): the script is executed
     through the arm-none-eabi-gcc symlink of the wrapper toolchain directory
     (argv[0] carries the tool name). GN has no per-module preprocessing hook
     like the fbb module.cmake, so the board toolchain path points at that
     directory: the wrapper receives the REAL command line assembled by GN
     (defines, include dirs, cflags, -imacros config.h), runs gcc -E (depfile
     flags forwarded so the dependency file keeps tracking the real headers),
     invokes this same script in mode 1 on the expansion, then compiles the
     rewritten file with the original flags. When
     LOSCFG_KERNEL_HPL_SCRIPT_PREPROCESSOR is not enabled the tool is executed
     transparently.
  3. Toolchain generation mode: argv = --gen-toolchain <product out dir>.
     Materialises the wrapper toolchain directory as a build-time artefact
     under the out dir (called once per "gn gen" from liteos.gni): the
     arm-none-eabi-gcc entry is a symlink to this script, the remaining tool
     names are symlinks to the real cross tools found in PATH. Nothing is
     stored in the repository.
'''

import sys
import os
import logging
import shutil
import re
import stat
import fcntl
import subprocess
import hashlib
sys.path.append(sys.path[0]+"/../")
from util.utils import Utils

LOG_FORMAT = '[%(funcName)s:%(lineno)d, %(levelname)s]: %(message)s'
logging.basicConfig(level=logging.NOTSET, format=LOG_FORMAT)

# example:
# do { OsHplLoggerHook(535, HPL_NOTICE, "A string, pointer, number: '%s', %p, %d, %f, %llx, %lx\n", randomString,
# &randomString, 512, pi, U64, Ul32); } while(0);
LOGGER_START = r'\s*do\s*\{\s*OsHplLoggerHook\([\s\S\}]+?\}\s*?while\s*\(0\)'
# [^\\] is for escape character.
FORMAT_STRING = r'OsHplLoggerHook\([\s\S]*?,[\s\S]*?,\s*(\(*\".*[^\\]\"\)*)[,)]+'
ANNOTATION_INFO = r'^\s*#'
FILE_PATH = r'.*?\s*"(.*?)"'
FORMAT_STRING_WITH_BRACKET = r'^\(*(\".*\")\)*$'

# example:    do { OsHplLoggerHook(59
LOG_LINE = r'OsHplLoggerHook\(\s*([\d]+)'

'''
exapmle:
    do { OsHplLoggerHook(
# 59 "HPL/targets/qemu-virt-a53/main.c"
                                              59
'''
LOG_LINE_WITH_COMMENT = r'OsHplLoggerHook\(\s#.*?".*?"\s*([\d]+)'

FILE_NOTE = [
    "/* This is LiteOS high performance log static info metadata file.\n",
    " * The file is generated by scripts and forbidden to modify manually.\n",
    " * Each log take up 4 lines to record static info for decompressor.\n",
    " * Line 1: The file which invoke high performance log interface.\n",
    " * Line 2: The file line number where invoke high performance log interface.\n",
    " * Line 3: The log format string.\n",
    " * Line 4: The analysis result of format string and format id. */\n",
    "\n",
]

METADATA_STRUCTURE = [
    "#include \"los_typedef.h\"\n",
    "#pragma pack(push, 4)\n"
    "typedef struct {\n",
    "    CHAR* filename;\n",
    "    UINT32 linenum;\n",
    "    CHAR* formatString;\n",
    "    UINT64 analysis;\n",
    "} HplMetadataInfo;\n",
    "#pragma pack(pop)\n"
    "#define ATTR_SECTION1 __attribute__((section(\".hpl_metadata.1\")))\n",
    "#define ATTR_SECTION2 __attribute__((section(\".hpl_metadata.2\")))\n",
    "#define ATTR_USED __attribute__((used))\n\n",
]

METADATA_INFO_BEFORE = [
    "const HplMetadataInfo g_metadata[] ATTR_SECTION2 ATTR_USED = {\n",
]

PROCESSOR_BIT = 0
MODULE_NUM = 0
FILE_STATIC_INFO = False

ARGS_TYPE_4_BYTES = 0
ARGS_TYPE_8_BYTES = 1
ARGS_TYPE_STRING_BYTES = 2
ARGS_TYPE_DOUBLE_BYTES = 3
ARGS_TYPE_UNSUPPORTED = 4

ARGS_INVALID_ANALYSIS = 0xFEFEFEFE
FUNC_DICT = []
FUNC_SEARCH_LINE = 0


def set_args_num_and_type(args_type, new_type, posi, dynamic_num):
    '''
    Set new args type and num.
    '''
    # Dynamic width or precision is ahead of arguments.
    for _ in range(0, dynamic_num):
        args_type |= (ARGS_TYPE_4_BYTES) << (posi * 2)
        posi += 1
    args_type |= (new_type) << (posi * 2)
    posi += 1
    return args_type, posi


def check_width_or_precision(fmt, next_idx):
    '''
    Judge if format string has width or precision control.
    '''
    has_width_or_precision = False
    dynamic_num = 0
    if fmt[next_idx] == '#':
        next_idx += 1
        has_width_or_precision = True

    if fmt[next_idx] == '*':
        next_idx += 1
        has_width_or_precision = True
        dynamic_num += 1
    else:
        # Fixed width.
        while (fmt[next_idx] >= '0' and fmt[next_idx] <= '9') or fmt[next_idx] == '-' or fmt[next_idx] == '+':
            has_width_or_precision = True
            next_idx += 1

    if fmt[next_idx] == '.':
        next_idx += 1
        if fmt[next_idx] == '*':
            dynamic_num += 1
            has_width_or_precision = True
            next_idx += 1
        else:
            # Fixed precision.
            while (fmt[next_idx] >= '0' and fmt[next_idx] <= '9') or fmt[next_idx] == '-' or fmt[next_idx] == '+':
                has_width_or_precision = True
                next_idx += 1
    return next_idx, has_width_or_precision, dynamic_num


def analysis_arch_dynamic_args(param_type, param_number, dynamic_num):
    '''
    Analysis dynamic width arguments with different architecture.
    '''
    if PROCESSOR_BIT == 32:
        param_type, param_number = set_args_num_and_type(param_type, ARGS_TYPE_4_BYTES, param_number, dynamic_num)
    else:
        param_type, param_number = set_args_num_and_type(param_type, ARGS_TYPE_8_BYTES, param_number, dynamic_num)
    return param_type, param_number


def analysis_long_type_args(fmt, next_idx, args_type, args_num, dynamic_args_num):
    '''
    Analysis long type arguments.
    '''
    if (fmt[next_idx + 1] == 'l') and (fmt[next_idx + 2] in ('x', 'd', 'u', 'X')):
        args_type, args_num = set_args_num_and_type(args_type, ARGS_TYPE_8_BYTES, args_num, dynamic_args_num)
        next_idx += 3
    elif fmt[next_idx + 1] in ('x', 'd', 'u', 'X'):
        args_type, args_num = analysis_arch_dynamic_args(args_type, args_num, dynamic_args_num)
        next_idx += 2
    elif fmt[next_idx + 1] == 'f':
        args_type, args_num = set_args_num_and_type(args_type, ARGS_TYPE_DOUBLE_BYTES, args_num, dynamic_args_num)
        next_idx += 2
    else:
        Utils.err_exit("format string illegal {0}".format(fmt))
        next_idx += 1
    return next_idx, args_type, args_num


def analysis_is_int_type_args(args_type):
    '''
    Analysis int type arguments, Treat 'h' and 'c' as int type because compiler passed as int type.
    '''
    if args_type in ('d', 'x', 'u', 'c', 'X', 'h', 'i', 'z'):
        return True
    return False


def check_args_valid(format_string, number, args_type):
    '''
    Check if argumetns valid.
    '''
    # Maximum argmuments number is 28.
    if number > 28:
        Utils.err_exit("file: {0}, arugments number overflow 28: fmt:{1}, args num {2}".format(sys.argv[2], \
                       format_string, number))
    return number | args_type << 8


def skip_bracket(fmt_string):
    '''
    Delete unused bracket.
    eg. HP_LOG(HPL_NOITCE, ("hello world"));
    '''
    matches = re.search(FORMAT_STRING_WITH_BRACKET, fmt_string)
    return matches.group(1)


def analysis_args(fmt):
    '''
    Analysis format string to calculate arguments number and type.
    '''
    args_num = 0
    args_type = 0
    dynamic_num = 0
    has_width_or_precision = False

    i = 0
    while i < len(fmt):
        if fmt[i] != '%':
            i += 1
            continue

        # escape character: %%
        if fmt[i + 1] == '%':
            i += 2
            continue

        # If has width or precision type, next variable is added by last circulation and i variable is not changed.
        if not has_width_or_precision:
            next_idx = i + 1

        # Treat '%  x' as '%x' to match with standard print.
        while fmt[next_idx] == ' ':
            next_idx += 1
            continue
        if analysis_is_int_type_args(fmt[next_idx]):
            args_type, args_num = set_args_num_and_type(args_type, ARGS_TYPE_4_BYTES, args_num, dynamic_num)
            next_idx += 1
        elif fmt[next_idx] == 'j': # custom formative type for function and line
            next_idx += 1
        elif fmt[next_idx] == 'f' or fmt[next_idx] == 'g':
            args_type, args_num = set_args_num_and_type(args_type, ARGS_TYPE_DOUBLE_BYTES, args_num, dynamic_num)
            next_idx += 1
        elif fmt[next_idx] == 'p':
            args_type, args_num = analysis_arch_dynamic_args(args_type, args_num, dynamic_num)
            next_idx += 1
        elif fmt[next_idx] == 's':
            args_type, args_num = set_args_num_and_type(args_type, ARGS_TYPE_STRING_BYTES, args_num, dynamic_num)
            next_idx += 1
        elif fmt[next_idx] == 'l':
            next_idx, args_type, args_num = analysis_long_type_args(fmt, next_idx, args_type, args_num, dynamic_num)
        else:
            # Check if format has dynamic width or precision. if already has dynamic width or precision, it indicates
            # that it is not a illegal dynamic width or precision. such as "%*.*kkkkk".
            if has_width_or_precision:
                has_width_or_precision = False
                dynamic_num = 0
                i = next_idx
                Utils.err_exit("format string illegal {0}".format(fmt))
                continue

            next_idx, has_width_or_precision, dynamic_num = check_width_or_precision(fmt, next_idx)
            # If has dynamic width or precision, we need continue to verify the following character.
            if has_width_or_precision:
                continue

            # Illegal format string abort
            Utils.err_exit("format string illegal {0}".format(fmt))
            next_idx += 1

        # Dynamic width and precison preiod of validity is just one-off.
        i = next_idx
        has_width_or_precision = False
        dynamic_num = 0
    return check_args_valid(fmt, args_num, args_type)


def extract_format_string(fmt_info):
    '''
    Extract format string.
    '''
    qeuotation_cnt = 0
    out_fmt = ''
    origin_fmt = ''
    for i in range(0, len(fmt_info)):
        if fmt_info[i] == '"' and fmt_info[i - 1] != '\\':
            qeuotation_cnt += 1
            origin_fmt += fmt_info[i]
            continue

        if qeuotation_cnt == 0:
            origin_fmt += fmt_info[i]
            continue

        if qeuotation_cnt % 2 == 0:
            if fmt_info[i] != ' ' and fmt_info[i] != ')':
                break
        else:
            out_fmt += fmt_info[i]

        origin_fmt += fmt_info[i]
    return out_fmt, origin_fmt


def replace_long_type(format_string):
    '''
    Extract long type parameters and replace it with long long type. Windows use LLP64 data model and long takes up 4
    Bytes. Windows "%lx" is used for long type which takes up 4 bytes but 64 bits LiteOS "%lx" takes up 8 Bytes.
    '''
    if PROCESSOR_BIT == 32:
        return format_string

    pattern = r'%([\*]?\d*\.?[\*]?\d*)l([duxX]+)'
    replacement = r'%\1ll\2'
    content = re.sub(pattern, replacement, format_string)
    return content


def get_log_function_name(log_line):
    '''
    Get function string according to log row number.
    '''
    global FUNC_SEARCH_LINE
    log_num = log_line

    for i in range(FUNC_SEARCH_LINE, len(FUNC_DICT), 2):
        if log_num > int(FUNC_DICT[len(FUNC_DICT) - 1]):
            i = len(FUNC_DICT) - 2
            break

        if (log_num > int(FUNC_DICT[i + 1]) and log_num < int(FUNC_DICT[i + 3])):
            break

    FUNC_SEARCH_LINE = i
    return FUNC_DICT[i]


def modify_format_string(log_code, metadata_file, format_id, source_path, function_name, is_emulation):
    '''
    Extract format string and record static info. Replace format string with analysis result
    Each format string take up 4 line in metadata: source path, line number, format string and analysis result.
    '''
    line_num = re.search(LOG_LINE, log_code)
    if not line_num:
        line_num = re.search(LOG_LINE_WITH_COMMENT, log_code)
    matches = re.search(FORMAT_STRING, log_code)
    if not matches or not line_num:
        Utils.err_exit("log code is illegal: {0}, source file: {1}".format(log_code, source_path))

    format_info = matches.group(1)
    format_analisys, origin_format = extract_format_string(format_info)
    analysis = analysis_args(format_analisys)
    format_output = skip_bracket(origin_format)
    format_output = replace_long_type(format_output)

    module_format_id = (MODULE_NUM << 24) | format_id
    log_code = log_code.replace(origin_format, hex(module_format_id) + ', ' + hex(analysis))
    # Delete line parameter.
    log_code = re.sub(r"#?\s*" + str(line_num.group(1)) + r"[\s\S]*?,", '', log_code, count=1)

    if is_emulation == "FALSE":
        if FILE_STATIC_INFO:
            # Record source file path info
            log_info = source_path + '\n'
        else:
            log_info = '\"***\"' + '\n'

        # Record function string and log line
        log_info += function_name + ' ' + str(line_num.group(1)) + '\n'

        # Record static format string
        log_info += format_output + '\n'

        # Record analysis result and format_id
        log_info += hex(analysis) + ' ' + hex(module_format_id) + '\n'
        metadata_file.write(log_info)
    else:
        # Record source file path info
        log_info = "    {.filename = " + source_path + ',\n'

        # Record the line num of log
        log_info += "     .linenum = " + str(line_num.group(1)) + ',\n'

        # Record static format string
        log_info += "     .formatString = " + format_output + ',\n'

        # Record analysis result
        log_info += "     .analysis = " + hex(analysis) + '},\n'
        metadata_file.write(log_info)

    return log_code


def write_metadata_header(metadata_fd, emulation_flag):
    '''
    Write metadata file annotation header.
    '''
    metadata_fd.writelines(FILE_NOTE)

    if emulation_flag == "TRUE":
        metadata_fd.writelines(METADATA_STRUCTURE)
        metadata_fd.writelines(METADATA_INFO_BEFORE)
    metadata_fd.flush()


def get_atomic_fmt_id(atomic_fd, cnt):
    '''
    Get an unique id for this log.
    '''
    # Lock file to ensure format Id is global unique and progressive increase.
    fcntl.flock(atomic_fd.fileno(), fcntl.LOCK_EX)
    atomic_fd.seek(0, 0)
    atomic_cnt = atomic_fd.read()
    if not atomic_cnt:
        atomic_cnt = 0
    else:
        atomic_cnt = int(atomic_cnt)
    atomic_fd.seek(0, 0)
    atomic_fd.write(str(atomic_cnt + cnt))
    atomic_fd.flush()
    fcntl.flock(atomic_fd.fileno(), fcntl.LOCK_UN)
    if atomic_cnt > 0xFFFFFF or atomic_cnt < 0:
        Utils.err_exit("invalid format id {0}".format(atomic_cnt))
    return atomic_cnt


def prase_file(preprocess_file, metadata_fd, emulation_flag, atomic_fd):
    '''
    Prase compiler preprocess file.
    '''
    ori_file = preprocess_file + '.i'
    os.rename(preprocess_file, ori_file)

    # open with write only | open with creat | open with trunc
    file_flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    # Write by owner | Read by owner | Read by group | Read by others
    file_modes = stat.S_IWUSR | stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH
    with os.fdopen(os.open(preprocess_file, file_flags, file_modes), 'w') as modify_handle:
        with os.fdopen(os.open(ori_file, os.O_RDONLY), 'r') as ori_handle:
            lines = ori_handle.read()

            # extrace "OsHplLoggerHook" line number in .i preprocessor file
            spilt_lines = lines.split('\n')
            log_matches_line = []
            for line_num, line in enumerate(spilt_lines, 1):
                count = line.count("OsHplLoggerHook")
                log_matches_line.extend([line_num] * count)

            # Search source file path and high performance log code.
            search = re.search(FILE_PATH, lines)
            if search:
                source_path = search.group(1)
                source_path = os.path.basename(source_path)
                source_path = '"' + source_path + '"'
            else:
                Utils.err_exit("not find file name in preprocess file: {0}".format(preprocess_file))

            # Search all high performance log interface.
            matches = re.findall(LOGGER_START, lines, re.M)

            fmt_id = get_atomic_fmt_id(atomic_fd, len(matches))
            # Analysis all log code and inject modified code.
            i = 1 # The 0 index of log_matches_line is declaration of OsHplLoggerHook, jump over it!
            for match in matches:
                if fmt_id == 0:
                    write_metadata_header(metadata_fd, emulation_flag)
                modify = modify_format_string(match, metadata_fd, fmt_id, source_path, \
                                              get_log_function_name(log_matches_line[i]), emulation_flag)
                fmt_id += 1
                i += 1
                lines = lines.replace(match, modify)
            modify_handle.writelines(lines)


def extrace_function_line_info(src_file):
    '''
    Extrace function string and line number info.
    '''
    global FUNC_DICT
    extrace_command = "ctags -x " + src_file + " | grep -Iw function | tr -s ' ' | cut -d' ' -f 1,3 | sort -k 2 -n"
    extrace_out_text, extrace_return_code = Utils.run_shell_return(extrace_command, None)
    if extrace_return_code not in (0, 1):
        Utils.err_exit("{0} return {1}".format(extrace_command, extrace_return_code))

    array = re.split(r'[\s]+', extrace_out_text)
    array.pop()
    FUNC_DICT = array


