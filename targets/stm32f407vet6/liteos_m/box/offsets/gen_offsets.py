#!/usr/bin/env python3
"""
Linux-style asm-offsets generator for the BOX feature.

Compiles los_offsets.c to assembly (arm-none-eabi-gcc -S) with the same
include set the kernel build uses, then converts the emitted @@BOX_OFFSET@@
lines into a C header of #defines for the ported asm to include.

Wired into the build as a GN action (box/offsets/BUILD.gn): runs on every
build and regenerates box/kernel/los_offsets.h whenever a struct-defining
input changes. The write is compare-and-swap - identical content leaves the
header (and its mtime) untouched, so an unchanged struct costs nothing.
Because this build has no depfiles, the --touch list (the consumer sources)
is mtime-bumped only on real changes: that bump is what drives their
recompilation (design doc pitfall 27).

Usage (manual form, equivalent to the action):
  gen_offsets.py --kernel-dir <kernel/liteos_m> --out-dir <hb product out>
                 --source <los_offsets.c> --output <los_offsets.h>
                 [--stamp <ninja output>] [--touch <consumer source>]...
"""
import argparse
import os
import re
import subprocess
import sys

MARKER = re.compile(r'^@@BOX_OFFSET@@\s+(\S+)\s+[$#]?(\S+)\s*$')

# Include set mirrored from the kernel compile command. Refresh via:
#   ninja -t commands obj/kernel/liteos_m/kernel/base/base.los_task.o | head -1
KERNEL_REL_INCS = [
    "kernel/base/include",
    "kernel/include",
    "kernel/extended/include",
    "arch/arm/common",
    "arch/arm/cortex_m",
    "arch/arm/include",
    "arch/include",
    "compat/cmsis",
    "targets/stm32f407vet6/liteos_m/board",
    "targets/stm32f407vet6/liteos_m/board/include",
    "targets/stm32f407vet6/liteos_m/board/driver",
]

LITEOS_REL_INCS = [
    "commonlibrary/utils_lite/include",
    "third_party/cmsis/CMSIS/Core/Include",
    "third_party/cmsis/CMSIS/RTOS2/Include",
    "third_party/musl/porting/liteos_m/kernel/include",
    "third_party/bounds_checking_function/include",
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kernel-dir", required=True, help="kernel/liteos_m root")
    ap.add_argument("--out-dir", required=True, help="hb product out dir (holds config.h)")
    ap.add_argument("--source", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--stamp", default=None,
                    help="ninja-declared output file; created/touched only on real changes")
    ap.add_argument("--touch", action="append", default=[],
                    help="consumer source to mtime-bump on real changes (repeatable)")
    a = ap.parse_args()

    liteos_root = os.path.abspath(os.path.join(a.kernel_dir, "..", ".."))
    incs = []
    for p in KERNEL_REL_INCS:
        incs += ["-I", os.path.join(a.kernel_dir, p)]
    for p in LITEOS_REL_INCS:
        incs += ["-I", os.path.join(liteos_root, p)]

    asm_file = a.output + ".s"
    cmd = (["arm-none-eabi-gcc", "-S",
            "-mcpu=cortex-m4", "-mthumb", "-std=c99",
            "-D__LITEOS__", "-D__LITEOS_M__", "-D_XOPEN_SOURCE=700", "-DOHOS_DEBUG",
            "-DGEN_OFFSETS",
            "-imacros", os.path.join(a.out_dir, "config.h")]
           + incs + ["-o", asm_file, a.source])
    subprocess.check_call(cmd)

    defines = {}
    with open(asm_file) as f:
        for line in f:
            m = MARKER.match(line.strip())
            if m:
                defines[m.group(1)] = m.group(2)
    os.unlink(asm_file)

    if not defines:
        sys.exit("error: no @@BOX_OFFSET@@ lines found - check compile flags "
                 "(is LOSCFG_BOX enabled in --out-dir/config.h?)")

    content = ("/* GENERATED by gen_offsets.py - do not edit. */\n"
               "#ifndef _LOS_BOX_OFFSETS_H\n#define _LOS_BOX_OFFSETS_H\n\n")
    for k in sorted(defines):
        content += "#define %-28s %s\n" % (k, defines[k])
    content += "\n#endif /* _LOS_BOX_OFFSETS_H */\n"

    for k in sorted(defines):
        print("  %-28s %s" % (k, defines[k]))

    changed = True
    if os.path.exists(a.output):
        with open(a.output) as f:
            changed = (f.read() != content)
    stamp_missing = a.stamp and not os.path.exists(a.stamp)

    if not changed and not stamp_missing:
        print("gen_offsets: %s unchanged - no write, no touch" % a.output)
        return

    if changed:
        with open(a.output, "w") as f:
            f.write(content)
        for t in a.touch:
            os.utime(t, None)
        print("gen_offsets: wrote %s (%d offsets), touched %d consumer(s)"
              % (a.output, len(defines), len(a.touch)))
        print("gen_offsets: *** OFFSETS CHANGED - run the build AGAIN (or")
        print("gen_offsets: *** rm -rf out/.../obj) before flashing! The")
        print("gen_offsets: *** same-build recompile is NOT reliable: this")
        print("gen_offsets: *** build system has no depfiles, and ninja's")
        print("gen_offsets: *** initial mtime scan happens before this")
        print("gen_offsets: *** action runs (design doc pitfall 27).")
    else:
        print("gen_offsets: header unchanged (stamp first run)")
    if a.stamp:
        with open(a.stamp, "a"):
            pass
        os.utime(a.stamp, None)


if __name__ == "__main__":
    main()
